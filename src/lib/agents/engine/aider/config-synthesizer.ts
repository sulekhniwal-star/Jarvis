import { CodingTaskContext } from "../types";
import { AiderCliOptions } from "./types";

export const DEFAULT_AIDER_MODEL = "openrouter/qwen/qwen-2.5-coder-32b-instruct";
export const OPENROUTER_DEFAULT_BASE_URL = "https://openrouter.ai/api/v1";

/**
 * Synthesizes CLI command-line arguments for headless, batch execution of Aider.
 */
export function synthesizeAiderArgs(
  context: CodingTaskContext,
  options?: Partial<AiderCliOptions>
): string[] {
  const args: string[] = [];

  // Core headless non-interactive flags
  args.push("--yes-always");
  args.push("--no-show-model-warnings");
  args.push("--no-analytics");
  args.push("--no-check-update");

  // Model & provider configuration
  const model =
    options?.modelConfig?.model ||
    context.environmentVariables?.AIDER_MODEL ||
    DEFAULT_AIDER_MODEL;
  args.push("--model", model);

  const apiBase =
    options?.modelConfig?.apiBase ||
    context.environmentVariables?.OPENAI_API_BASE ||
    (model.startsWith("openrouter/") ? OPENROUTER_DEFAULT_BASE_URL : undefined);
  if (apiBase) {
    args.push("--openai-api-base", apiBase);
  }

  const apiKey =
    options?.modelConfig?.apiKey ||
    context.environmentVariables?.OPENROUTER_API_KEY ||
    context.environmentVariables?.OPENAI_API_KEY;
  if (apiKey) {
    args.push("--openai-api-key", apiKey);
  }

  // Edit format if specified
  if (options?.modelConfig?.editFormat) {
    args.push("--edit-format", options.modelConfig.editFormat);
  }

  // Git auto-commit policy
  if (options?.autoCommits === false) {
    args.push("--no-auto-commits");
  } else if (options?.commitPrompt) {
    args.push("--commit-prompt", options.commitPrompt);
  }

  // Read-only context files
  if (options?.readOnlyFiles && options.readOnlyFiles.length > 0) {
    for (const readOnly of options.readOnlyFiles) {
      args.push("--read", readOnly);
    }
  }

  // Scoped instructions / prompt
  if (options?.messageFile) {
    args.push("--message-file", options.messageFile);
  } else {
    const message = options?.message || context.scopedInstructions;
    args.push("--message", message);
  }

  // Extra CLI flags if requested
  if (options?.extraArgs && options.extraArgs.length > 0) {
    args.push(...options.extraArgs);
  }

  // Strict positional target files from allowedFilePatterns
  const targetFiles = options?.targetFiles || context.allowedFilePatterns;
  for (const file of targetFiles) {
    args.push(file);
  }

  return args;
}

/**
 * Generates `.aider.conf.yml` YAML configuration string from context and options.
 */
export function generateAiderYamlConfig(
  context: CodingTaskContext,
  options?: Partial<AiderCliOptions>
): string {
  const model =
    options?.modelConfig?.model ||
    context.environmentVariables?.AIDER_MODEL ||
    DEFAULT_AIDER_MODEL;

  const lines: string[] = [];
  lines.push("# Auto-generated by Jarvis Aider Configuration Synthesizer");
  lines.push(`model: ${model}`);
  lines.push("yes-always: true");
  lines.push("show-model-warnings: false");
  lines.push("analytics: false");
  lines.push("check-update: false");

  if (options?.autoCommits === false) {
    lines.push("auto-commits: false");
  } else {
    lines.push("auto-commits: true");
  }

  if (options?.commitPrompt) {
    lines.push(`commit-prompt: "${options.commitPrompt.replace(/"/g, '\\"')}"`);
  }

  const apiBase =
    options?.modelConfig?.apiBase ||
    context.environmentVariables?.OPENAI_API_BASE ||
    (model.startsWith("openrouter/") ? OPENROUTER_DEFAULT_BASE_URL : undefined);
  if (apiBase) {
    lines.push(`openai-api-base: ${apiBase}`);
  }

  if (options?.readOnlyFiles && options.readOnlyFiles.length > 0) {
    lines.push("read:");
    for (const file of options.readOnlyFiles) {
      lines.push(`  - ${file}`);
    }
  }

  return lines.join("\n") + "\n";
}

/**
 * Class wrapper for Aider configuration synthesizer.
 */
export class AiderConfigSynthesizer {
  public synthesizeArgs(
    context: CodingTaskContext,
    options?: Partial<AiderCliOptions>
  ): string[] {
    return synthesizeAiderArgs(context, options);
  }

  public generateYamlConfig(
    context: CodingTaskContext,
    options?: Partial<AiderCliOptions>
  ): string {
    return generateAiderYamlConfig(context, options);
  }
}
